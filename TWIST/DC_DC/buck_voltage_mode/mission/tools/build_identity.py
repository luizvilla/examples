"""Compute the mission firmware's build identity.

Usage:
    tools/build_identity.py <header>   write a build_identity.h for the firmware
    tools/build_identity.py --json     print the identity as JSON

The identity has three parts:
    commit       git commit of the repository holding the mission
    dirty        true if the hashed sources differ from that commit
    source_hash  SHA-256 of the hashed sources, first 16 hex digits

The hashed sources are everything in firmware/ (except the generated
build_identity.h) plus data_objects.yaml. The hash depends only on file
paths and contents, so the same sources always give the same hash.
"""
import argparse
import hashlib
import json
import pathlib
import subprocess
import sys

MISSION = pathlib.Path(__file__).resolve().parent.parent
GENERATED = "build_identity.h"


def hashed_files(mission=MISSION):
    files = [p for p in (mission / "firmware").rglob("*")
             if p.is_file() and p.name != GENERATED and "__pycache__" not in p.parts]
    files.append(mission / "data_objects.yaml")
    return sorted(files, key=lambda p: p.relative_to(mission).as_posix())


def source_hash(mission=MISSION):
    digest = hashlib.sha256()
    for path in hashed_files(mission):
        digest.update(path.relative_to(mission).as_posix().encode() + b"\0")
        digest.update(path.read_bytes() + b"\0")
    return digest.hexdigest()[:16]


def git(mission, *args):
    result = subprocess.run(["git", *args], cwd=mission, capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else None


def identity(mission=MISSION):
    commit = git(mission, "rev-parse", "HEAD")
    if commit is None:
        return {"commit": "unknown", "dirty": True, "source_hash": source_hash(mission)}
    paths = [p.relative_to(mission).as_posix() for p in hashed_files(mission)]
    status = git(mission, "status", "--porcelain", "--", *paths)
    return {"commit": commit, "dirty": bool(status), "source_hash": source_hash(mission)}


def header(ident):
    return (
        "/* GENERATED by tools/build_identity.py at build time. Do not commit. */\n"
        "#pragma once\n"
        f'#define BUILD_COMMIT "{ident["commit"]}"\n'
        f'#define BUILD_DIRTY {"true" if ident["dirty"] else "false"}\n'
        f'#define BUILD_SOURCE_HASH "{ident["source_hash"]}"\n'
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("header", nargs="?", type=pathlib.Path, help="build_identity.h to write")
    group.add_argument("--json", action="store_true", help="print the identity as JSON")
    args = parser.parse_args(argv)
    ident = identity()
    if args.json:
        print(json.dumps(ident))
    else:
        args.header.write_text(header(ident))
        print(f"build identity: {ident['commit'][:12]}{' (dirty)' if ident['dirty'] else ''} sources {ident['source_hash']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
